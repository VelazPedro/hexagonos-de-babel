/// The look of a screen. Every screen has to be named here.
pub fn place_for(screen: Screen, bench: Option<Station>) -> Place {
    match screen {
        Screen::Title | Screen::NewGame | Screen::Look | Screen::Pause => Place::Library,
        Screen::Coop => Place::Rooms,
        Screen::Options | Screen::Controls => Place::Clockwork,
        Screen::Crafting => match bench {
            Some(Station::Forge) => Place::Forge,
            Some(Station::Binder) => Place::Binder,
            Some(Station::Alembic) => Place::Alembic,
            Some(Station::Scriptorium | Station::Chest) | None => Place::Library,
        },
        Screen::Build(_) => Place::Build,
        Screen::Chest => Place::Chest,
        Screen::Lamps => Place::Lamps,
        Screen::Scriptorium => Place::Scriptorium,
        Screen::Inventory => Place::Inventory,
        Screen::Skills => Place::Skills,
        Screen::Glossary => Place::Glossary,
        Screen::Map => Place::Map,
        Screen::Catalog => Place::Catalog,
        Screen::Reader => Place::Reader,
        Screen::GameOver => Place::Ashes,
        Screen::Stats => Place::Records,
        Screen::Ending | Screen::Credits => Place::Dawn,
    }
}

/// Whether the world still shows behind a screen.
pub fn sees_through(screen: Screen) -> bool {
    matches!(screen, Screen::Title | Screen::Pause | Screen::GameOver)
}

/// How far apart two colours are for the eye, from 1 to 21 (WCAG).
#[cfg(test)]
pub fn contrast(a: Rgba, b: Rgba) -> f32 {
    let light = |c: Rgba| {
        let channel = |v: u8| {
            let v = f32::from(v) / 255.0;
            if v <= 0.040_45 {
                v / 12.92
            } else {
                ((v + 0.055) / 1.055).powf(2.4)
            }
        };
        0.2126 * channel(c[0]) + 0.7152 * channel(c[1]) + 0.0722 * channel(c[2])
    };
    let (x, y) = (light(a), light(b));
    (x.max(y) + 0.05) / (x.min(y) + 0.05)
}
