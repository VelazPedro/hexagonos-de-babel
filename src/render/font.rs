#[derive(Clone, Copy, Debug)]
pub enum Mark {
    Acute,
    Tilde,
    Diaeresis,
}

/// Base glyph and mark of an accented letter.
pub fn decompose(c: char) -> (char, Option<Mark>) {
    use Mark::{Acute, Diaeresis, Tilde};
    match c {
        'á' => ('a', Some(Acute)),
        'é' => ('e', Some(Acute)),
        'í' => ('ı', Some(Acute)),
        'ó' => ('o', Some(Acute)),
        'ú' => ('u', Some(Acute)),
        'ü' => ('u', Some(Diaeresis)),
        'ñ' => ('n', Some(Tilde)),
        'Á' => ('A', Some(Acute)),
        'É' => ('E', Some(Acute)),
        'Í' => ('I', Some(Acute)),
        'Ó' => ('O', Some(Acute)),
        'Ú' => ('U', Some(Acute)),
        'Ü' => ('U', Some(Diaeresis)),
        'Ñ' => ('N', Some(Tilde)),
        other => (other, None),
    }
}

/// Pixel offsets of a mark relative to its centre column and top row.
pub fn mark_pixels(mark: Mark) -> &'static [(i32, i32)] {
    match mark {
        Mark::Acute => &[(0, 1), (1, 0)],
        Mark::Tilde => &[(-1, 1), (0, 0), (1, 1), (2, 0)],
        Mark::Diaeresis => &[(-1, 0), (1, 0)],
    }
}

#[derive(Clone, Copy, Debug, Default)]
pub struct Glyph {
    pub width: i32,
    pub rows: [u8; ROWS],
}

impl Glyph {
    pub fn ink(&self, x: i32, y: usize) -> bool {
        y < ROWS && (0..self.width).contains(&x) && self.rows[y] & (1 << x) != 0
    }
}

pub struct Font {
    glyphs: std::collections::HashMap<char, Glyph>,
}

impl Default for Font {
    fn default() -> Self {
        let glyphs = GLYPHS
            .iter()
            .map(|&(c, art)| {
                let mut g = Glyph::default();
                for (y, row) in art.split(' ').take(ROWS).enumerate() {
                    g.width = g.width.max(row.len() as i32);
                    for (x, p) in row.chars().enumerate() {
                        if p == '#' {
                            g.rows[y] |= 1 << x;
                        }
                    }
                }
                (c, g)
            })
            .collect();
        Font { glyphs }
    }
}

impl Font {
    pub fn glyph(&self, c: char) -> Option<&Glyph> {
        self.glyphs.get(&c)
    }

    pub fn advance(&self, c: char) -> i32 {
        if c == ' ' {
            return 4;
        }
        let (base, _) = decompose(c);
        // Accented i keeps room for its mark.
        if base == 'ı' {
            return 3;
        }
        self.glyph(base)
            .or_else(|| self.glyph('?'))
            .map_or(5, |g| g.width + 1)
    }

    pub fn width(&self, text: &str) -> i32 {
        text.chars().map(|c| self.advance(c)).sum::<i32>() - 1
    }

    /// Greedy word wrap to `max` pixels.
    pub fn wrap(&self, text: &str, max: i32) -> Vec<String> {
        let mut lines = Vec::new();
        for paragraph in text.split('\n') {
            let mut line = String::new();
            for word in paragraph.split(' ') {
                let candidate = if line.is_empty() {
                    word.to_string()
                } else {
                    format!("{line} {word}")
                };
                if self.width(&candidate) > max && !line.is_empty() {
                    lines.push(std::mem::replace(&mut line, word.to_string()));
                } else {
                    line = candidate;
                }
            }
            lines.push(line);
        }
        lines
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_spanish_text_and_rows_are_consistent() {
        let font = Font::default();
        let sample = "ABCDEFGHIJKLMNÑOPQRSTUVWXYZ abcdefghijklmnñopqrstuvwxyz \
                      áéíóúü ÁÉÍÓÚ ¿¡?! 0123456789 .,:;-+/()[]«»%\"'=*#<>_|×·";
        for c in sample.chars().filter(|&c| c != ' ') {
            let (base, _) = decompose(c);
            assert!(font.glyph(base).is_some(), "missing glyph {c}");
        }
        for &(c, art) in GLYPHS {
            let rows: Vec<&str> = art.split(' ').collect();
            assert_eq!(rows.len(), ROWS, "{c}");
            assert!(rows.iter().all(|r| r.len() == rows[0].len()), "{c}");
            assert!(rows[0].len() <= 5, "{c}");
        }
    }

    #[test]
    fn a_full_book_line_fits_the_screen() {
        let font = Font::default();
        let widest = "abcdefghijklmnñopqrstuvwxyz   ,.".repeat(3);
        let line: String = widest.chars().take(80).collect();
        assert!(font.width(&line) <= 440, "{}", font.width(&line));
    }
}
